#!/usr/bin/env python3
"""ab_stats.py [--write]: compute the pre-registered quantities of experiments/ab-2026-10 from ab_stats_v2.tsv and
ab_adjudication.tsv. No number in RESULTS.md or the paper's §3.8 is typed by hand; they come from here.
Run with: python3 -I experiments/ab-2026-10/ab_stats.py [--write]"""
import csv, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
STATS = os.path.join(HERE, 'ab_stats_v2.tsv'); ADJ = os.path.join(HERE, 'ab_adjudication.tsv')
EPS_DEFAULT = 300  # the paper's estimate, used only if no arm-D row is rejected (stated in the output)
PRED = {'P1': (0.09, 0.19, 0.05, 0.30), 'P2': 4/6, 'P3': (2.0, 3.7, 1.5), 'P4': (0.10, 0.40, 0.05), 'P5': (0.5, 2.0), 'P6': 0.05}

def load(path):
    if not os.path.exists(path): return []
    with open(path, encoding='utf-8') as f: return list(csv.DictReader(f, delimiter='\t'))

rows = load(STATS); adj = {r['key']: r for r in load(ADJ)}
if not rows: print('no rows in', STATS); sys.exit(1)
def num(x):
    try: return int(x)
    except (TypeError, ValueError): return 0
pairs = {}
for r in rows:
    k = r['brief'].replace('.md', '')
    arm = 'I' if r['worker'] == 'hub' else 'D'
    a = adj.get(r['key'], {})
    pairs.setdefault(k, {})[arm] = dict(r, verdict_hub=a.get('verdict', 'PENDING'), reason=a.get('reason', ''),
                                         A=num(a.get('admitted_chars', r.get('admitted_chars') or 0)),
                                         S=num(r['artifact_bytes']) or num(r['out_bytes']), b=num(r['brief_bytes']), o=num(r['o_bytes']))
missing = [k for k, p in sorted(pairs.items()) if 'D' not in p or 'I' not in p]
pending = [k for k, p in sorted(pairs.items()) for arm in ('D', 'I') if arm in p and p[arm]['verdict_hub'] == 'PENDING']
lines = []
P = lines.append
P('# A/B wave results (generated by ab_stats.py; do not edit by hand)\n')
P(f'Rows: {len(rows)}; pairs with both arms: {len(pairs) - len(missing)} of {len(pairs)}; missing arms: {missing or "none"}; pending adjudication: {pending or "none"}\n')
P('| pair | S_I | S_D | b | o_D | A_D | alpha_D | Delta_D | M = S_I/Delta_D | M\' = S_D/Delta_D | verdict_D | verdict_I | A_I | alpha_I |')
P('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
sum_SI = sum_SD = sum_b = sum_o = sum_A = sum_D = 0; acc_D = n_D = 0; eps_list = []; sum_AI = 0
for k, p in sorted(pairs.items()):
    D = p.get('D'); I = p.get('I')
    if not D: continue
    n_D += 1
    accD = D['verdict_hub'] == 'ACCEPT' and D['verdict'] == 'OK'
    if accD: acc_D += 1
    if D['verdict_hub'] == 'REJECT' or D['verdict'] != 'OK': eps_list.append(D['o'])
    A = D['A'] if accD else 0
    delta = D['b'] + D['o'] + A + (0 if accD else D['o'])
    SI = I['S'] if I else 0; AI = I['A'] if I and I['verdict_hub'] == 'ACCEPT' else 0
    alphaD = A / D['S'] if D['S'] else 0; alphaI = AI / SI if SI else 0
    M = SI / delta if delta and SI else 0; M2 = D['S'] / delta if delta else 0
    sum_SI += SI; sum_SD += D['S']; sum_b += D['b']; sum_o += D['o']; sum_A += A; sum_D += delta; sum_AI += AI
    P(f"| {k} | {SI} | {D['S']} | {D['b']} | {D['o']} | {A} | {alphaD:.3f} | {delta} | {M:.2f} | {M2:.2f} | {D['verdict_hub']}/{D['verdict']} | {(I['verdict_hub']+'/'+I['verdict']) if I else 'none'} | {AI} | {alphaI:.3f} |")
alpha = sum_A / sum_SD if sum_SD else 0; M = sum_SI / sum_D if sum_D else 0; bS = sum_b / sum_SD if sum_SD else 0; oS = sum_o / sum_SD if sum_SD else 0
ratio = sum_SI / sum_SD if sum_SD else 0; phat = acc_D / n_D if n_D else 0
eps = sum(eps_list) / len(eps_list) if eps_list else EPS_DEFAULT
SbarD = sum_SD / n_D if n_D else 0
denom = 1 - alpha - (sum_b + sum_o) / sum_SD if sum_SD else 0
pstar = eps / (eps + SbarD * denom) if denom > 0 else float('nan')
P('')
P(f'Pooled: alpha_D = {sum_A}/{sum_SD} = {alpha:.3f}; p_hat_D = {acc_D}/{n_D} = {phat:.2f}; M = {sum_SI}/{sum_D} = {M:.2f}; b/S_D = {bS:.3f}; o/S_D = {oS:.3f}; S_I/S_D = {ratio:.2f}; eps_bar = {eps:.0f}{" (paper estimate; no arm-D rejection)" if not eps_list else " (mean o of rejected arm-D rows)"}; p* = {pstar:.4f}; alpha_I = {sum_AI}/{sum_SI if sum_SI else 1} = {(sum_AI/sum_SI if sum_SI else 0):.3f}\n')
def mark(ok): return 'PASS' if ok else 'FAIL'
lo, hi, blo, bhi = PRED['P1']
P(f"- P1 alpha_D in [{lo}, {hi}]: {mark(lo <= alpha <= hi)} (band [{blo}, {bhi}]: {mark(blo <= alpha <= bhi)}; alpha_D >= 0.5: {'YES, 1/alpha bound withdrawn' if alpha >= 0.5 else 'no'})")
P(f"- P2 p_hat_D >= 4/6: {mark(phat >= PRED['P2'])}; p_hat_D <= 2/6: {'YES, 11/13 representativeness contradicted' if phat <= 2/6 else 'no'}")
lo, hi, floor = PRED['P3']
P(f"- P3 M in [{lo}, {hi}]: {mark(lo <= M <= hi)}; M < {floor}: {'YES, section 3.4 bound invalidated' if M < floor else 'no'}")
lo, hi, ocap = PRED['P4']
P(f"- P4 b/S_D in [{lo}, {hi}]: {mark(lo <= bS <= hi)}; o/S_D < {ocap}: {mark(oS < ocap)}")
lo, hi = PRED['P5']
P(f"- P5 S_I/S_D in [{lo}, {hi}]: {mark(lo <= ratio <= hi)}")
P(f"- P6 p* < {PRED['P6']}: {mark(pstar < PRED['P6'])}")
if missing or pending: P('\nINCOMPLETE: the marks above are provisional until every pair has both arms adjudicated.')
out = '\n'.join(lines)
print(out)
if '--write' in sys.argv:
    with open(os.path.join(HERE, 'RESULTS.md'), 'w', encoding='utf-8') as f: f.write(out + '\n')
    print('\nwritten RESULTS.md')

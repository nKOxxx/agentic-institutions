#!/usr/bin/env python3
"""List every sentence in sections 4, 5 and Appendix B of DRAFT.md that names a party, and whether it carries a file pointer.

A party word: reviewer, panel, chair, referee, worker, hub, adjudicator, author, reader, session.
A file pointer: a backticked path or filename, or the names INCIDENT_LOG / REVISION_LOG / NUMBER_SNAPSHOT, or the
literal "line(s) N". Sentences inside Table 1 are listed as table cells. Usage: python3 scripts/party_sentences.py DRAFT.md
"""
import re, sys

src = open(sys.argv[1], encoding="utf-8").read().split("\n")
PARTY = re.compile(r"\b(reviewers?|panels?|chair|referee|workers?|hub|adjudicat\w+|author|reader|sessions?)\b", re.I)
POINTER = re.compile(r"`[^`]*[./][^`]*`|INCIDENT_LOG|REVISION_LOG|NUMBER_SNAPSHOT|\blines? \d")
SPLIT = re.compile(r"(?<=[.!?])\s+(?=[A-Z\"(`§])")

def section_of(i, heads):
    cur = None
    for h_i, h in heads:
        if h_i <= i: cur = h
    return cur

heads = [(i, l) for i, l in enumerate(src) if l.startswith("## ")]
want = lambda h: h and (h.startswith("## 4") or h.startswith("## 5") or "Appendix B" in h)
rows = []
for i, line in enumerate(src):
    h = section_of(i, heads)
    if not want(h) or not line.strip() or line.startswith("## "): continue
    if line.startswith("|"):
        if set(line.replace("|", "").strip()) <= set("-: "): continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        for c in cells:
            if PARTY.search(c): rows.append((i + 1, h, "cell", bool(POINTER.search(c)), c))
        continue
    for s in SPLIT.split(line.strip()):
        if PARTY.search(s): rows.append((i + 1, h, "sentence", bool(POINTER.search(s)), s))

pointed = sum(1 for r in rows if r[3]); total = len(rows)
print(f"# party-naming sentences and cells in sections 4, 5 and Appendix B of {sys.argv[1]}")
print(f"# total {total}; with a file pointer {pointed}; without {total - pointed}. Generated by scripts/party_sentences.py; the rule is stated in INCIDENT_LOG (v1.10 block and the v1.10.1 addendum).")
for ln, h, kind, ptr, text in rows:
    print(f"L{ln}\t{'POINTED' if ptr else 'UNPOINTED'}\t{kind}\t{h[3:].strip()[:28]}\t{text}")
